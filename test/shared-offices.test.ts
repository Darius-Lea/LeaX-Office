import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const folder=mkdtempSync(join(tmpdir(),'leax-shared-'));process.env.HQ_DATA_DIR=folder;
const {db,authenticated}=await import('../src/store.ts');
const {sharedOfficeRequest:request,sharedUser}=await import('../src/shared-offices.ts');
after(()=>{db.close();rmSync(folder,{recursive:true,force:true});});
const password='synthetic-shared-office-password';let tick=1000000;
const call=(path:string,body?:any,token='',now=tick)=>request(path,body===undefined?'GET':'POST',body,token,'synthetic-ip',now);
const register=(handle:string)=>call('register',{handle,name:handle,password});
test('accounts, office isolation, one-use invitations, roles, live presence, removal and session expiry',()=>{
 const owner=register('owner'),friend=register('friend'),other=register('other');
 assert.ok(owner.token&&friend.token&&other.token);assert.equal(authenticated(owner.token!),false);
 const ownerToken=owner.token!,friendToken=friend.token!,otherToken=other.token!,address=owner.data.address,path='room/'+address;
 assert.notEqual(friend.data.address,address);assert.throws(()=>call(path,undefined,friendToken),/invitation required/);
 assert.throws(()=>call('me'),/Sign in/);
 assert.throws(()=>call(path+'/invite',{role:'owner'},ownerToken),/Choose a role/);
 const invite=call(path+'/invite',{role:'visitor'},ownerToken).data;
 assert.equal((db.prepare('SELECT hash FROM shared_invites').get() as any).hash===invite.invitation,false);
 assert.equal(call('join',{invitation:invite.invitation},friendToken).data.address,address);
 assert.throws(()=>call('join',{invitation:invite.invitation},otherToken),/expired/);
 assert.equal(call(path,undefined,friendToken).data.role,'visitor');
 assert.throws(()=>call(path+'/invite',{role:'coworker'},friendToken),/Only an owner/);
 call(path+'/enter',{},ownerToken);call(path+'/enter',{},friendToken);
 assert.equal(call(path,undefined,ownerToken).data.people.length,2);
 assert.throws(()=>call(path,undefined,otherToken),/invitation required/);
 call(path+'/message',{message:'Hello from the website'},friendToken);
 assert.equal(call(path,undefined,ownerToken).data.messages[0].body,'Hello from the website');
 assert.equal(call('room/'+other.data.address,undefined,otherToken).data.messages.length,0);
 const friendId=sharedUser(friendToken,tick).id;
 call(path+'/member',{userId:friendId,role:'co-owner'},ownerToken);
 assert.throws(()=>call(path+'/member',{userId:sharedUser(ownerToken,tick).id,role:'remove'},friendToken),/cannot be changed/);
 assert.throws(()=>call(path+'/invite',{role:'co-owner'},friendToken),/Choose a role/);
 const coworkerInvite=call(path+'/invite',{role:'coworker'},friendToken).data;
 call('join',{invitation:coworkerInvite.invitation},otherToken);
 assert.equal(call(path,undefined,otherToken).data.role,'coworker');
 assert.throws(()=>call(path+'/invite',{role:'visitor'},otherToken),/Only an owner/);
 call(path+'/member',{userId:friendId,role:'remove'},ownerToken);
 assert.throws(()=>call(path,undefined,friendToken),/invitation required/);
 assert.equal(call(path,undefined,ownerToken).data.people.length,1);
 const expired=call(path+'/invite',{role:'visitor'},ownerToken).data;
 assert.throws(()=>call('join',{invitation:expired.invitation},friendToken,tick+86400001),/expired/);
 call(path+'/enter',{},ownerToken,tick+86400002);
 assert.equal(call(path,undefined,ownerToken,tick+86450003).data.people.length,0);
 assert.equal(sharedUser(ownerToken,tick+8*86400000),undefined);
 call('logout',{},ownerToken);
 assert.throws(()=>call('me',undefined,ownerToken),/Sign in/);
});

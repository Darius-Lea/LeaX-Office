import {test,after} from 'node:test';import assert from 'node:assert/strict';import {mkdtempSync,rmSync} from 'node:fs';import {join} from 'node:path';import {tmpdir} from 'node:os';
const folder=mkdtempSync(join(tmpdir(),'leax-guest-conversation-'));process.env.HQ_DATA_DIR=folder;
const {db}=await import('../src/store.ts');const {sharedOfficeRequest:request}=await import('../src/shared-offices.ts');
after(()=>{db.close();rmSync(folder,{recursive:true,force:true});});
const now=Date.now(),password='guest-convo-fixture-password-1';
const call=(path:string,body?:any,token='',time=now)=>request(path,body===undefined?'GET':'POST',body,token,'fixture-ip',time);
test('guest joins the live conversation, appears in the people list, and messages are purged on revoke',()=>{
 const owner=call('register',{handle:'convoowner',name:'Host',password}),address=owner.data.address;
 call('room/'+address+'/enter',{},owner.token);
 call('room/'+address+'/message',{message:'Welcome to the tour'},owner.token);
 const link=call('guest-admin/create',{address,minutes:60,purpose:'walkthrough'},owner.token).data;
 const guest=call('guest/redeem',{invitation:link.invitation,name:'Investor'});assert.ok(guest.token);
 const convo=call('guest/conversation',undefined,guest.token).data;
 assert.equal(convo.messages.length,1);assert.equal(convo.messages[0].body,'Welcome to the tour');assert.equal(convo.messages[0].guest,0);
 assert.ok(convo.people.some((p:any)=>p.name==='Host'&&p.role==='owner'));
 assert.ok(convo.people.some((p:any)=>p.name==='Investor'&&p.role==='guest'));
 assert.equal(convo.members,undefined);
 call('guest/message',{message:'Hello from the lobby'},guest.token);
 const room=call('room/'+address,undefined,owner.token).data;
 assert.equal(room.messages.length,2);assert.equal(room.messages[1].body,'Hello from the lobby');assert.equal(room.messages[1].guest,1);assert.equal(room.messages[1].name,'Investor');
 assert.ok(room.people.some((p:any)=>p.name==='Host'&&p.role==='owner'));
 assert.ok(room.people.some((p:any)=>p.name==='Investor'&&p.role==='guest'&&p.id===null));
 const convo2=call('guest/conversation',undefined,guest.token).data;
 assert.deepEqual(convo2.messages.map((m:any)=>m.body),['Welcome to the tour','Hello from the lobby']);
 assert.throws(()=>call('guest/message',{message:'   '},guest.token),/Write a message/);
 assert.throws(()=>call('guest/message',{message:'x'.repeat(2001)},guest.token),/2000/);
 assert.throws(()=>call('guest/message',{message:'hi'},'bad-token'),/ended/);
 assert.throws(()=>call('guest/conversation',undefined,'bad-token'),/ended/);
 call('guest-admin/revoke',{address,id:link.id},owner.token);
 assert.throws(()=>call('guest/conversation',undefined,guest.token),/ended/);
 const room2=call('room/'+address,undefined,owner.token).data;
 assert.deepEqual(room2.messages.map((m:any)=>m.body),['Welcome to the tour']);
 assert.ok(!room2.people.some((p:any)=>p.name==='Investor'));
});
test('guest messages expire with the link',()=>{
 const owner=call('register',{handle:'convoexpiry',name:'Host Two',password}),address=owner.data.address;
 call('room/'+address+'/enter',{},owner.token);
 const link=call('guest-admin/create',{address,minutes:5,purpose:'interview'},owner.token).data;
 const guest=call('guest/redeem',{invitation:link.invitation,name:'Candidate'});assert.ok(guest.token);
 call('guest/message',{message:'Thanks for the tour'},guest.token);
 assert.equal(call('room/'+address,undefined,owner.token).data.messages.length,1);
 assert.throws(()=>call('guest/conversation',undefined,guest.token,now+300001),/ended/);
 const room=call('room/'+address,undefined,owner.token,now+300001).data;
 assert.equal(room.messages.length,0);
 assert.ok(!room.people.some((p:any)=>p.name==='Candidate'));
});

import {test,after} from 'node:test';import assert from 'node:assert/strict';import {mkdtempSync,rmSync} from 'node:fs';import {join} from 'node:path';import {tmpdir} from 'node:os';
const folder=mkdtempSync(join(tmpdir(),'leax-phone-invites-'));process.env.HQ_DATA_DIR=folder;
const {db}=await import('../src/store.ts');const {sharedOfficeRequest:R,sharedUser}=await import('../src/shared-offices.ts');
after(()=>{db.close();rmSync(folder,{recursive:true,force:true});});
const password='Phone-Invite-Test-2026!';let time=Date.now();const req=(path:string,data:any,token:string)=>R(path,data===undefined?'GET':'POST',data,token,'local',time).data;
const reg=(handle:string)=>R('register','POST',{handle,name:handle,password},'','local',time);
const unusedInvites=(roomId:string)=>(db.prepare('SELECT count(*) AS n FROM shared_invites WHERE room_id=? AND used_by IS NULL').get(roomId) as any).n;
test('phone invite by number: accept grants visitor membership and lands the guest in the live room state',()=>{
 const a=reg('invite-host'),b=reg('invite-guest');const at=a.token!,bt=b.token!,aRoom=a.data.address,bRoom=b.data.address;
 const aUser=sharedUser(at),bUser=sharedUser(bt);
 const guestCompany=req('phone/company',{address:bRoom,save:true,name:'Guest Company',listed:true,accepting:true},bt);
 const hostRoomId=(db.prepare('SELECT id FROM shared_rooms WHERE address=?').get(aRoom) as any).id;
 req('room/'+aRoom+'/message',{message:'Host note posted before the invite'},at);
 const invite=req('phone/invite',{address:aRoom,number:guestCompany.number,meeting:true},at);
 assert.equal(invite.kind,'invite');assert.equal(invite.status,'Ringing');assert.equal(invite.roomAddress,aRoom);assert.equal(invite.meeting,false);
 assert.equal(unusedInvites(hostRoomId),1);
 const inbox=req('phone/inbox',undefined,bt);assert.equal(inbox.calls[0].id,invite.id);assert.equal(inbox.calls[0].kind,'invite');assert.equal(inbox.calls[0].incoming,true);
 assert.throws(()=>req('phone/answer',{id:invite.id},bt),/office invitation/);
 assert.throws(()=>req('phone/invite-accept',{id:invite.id},at),/Only the invited person/);
 const accepted=req('phone/invite-accept',{id:invite.id},bt);assert.equal(accepted.address,aRoom);assert.equal(accepted.meeting,false);
 assert.equal(unusedInvites(hostRoomId),0);
 const room=req('room/'+aRoom,undefined,bt);assert.equal(room.role,'visitor');
 assert.ok(room.messages.some((m:any)=>m.body==='Host note posted before the invite'));
 assert.ok(req('me',undefined,bt).offices.some((o:any)=>o.address===aRoom&&o.role==='visitor'));
 assert.throws(()=>req('phone/invite-accept',{id:invite.id},bt),/no longer ringing/);
 const afterAccept=req('phone/inbox',undefined,at).calls.find((c:any)=>c.id===invite.id);assert.equal(afterAccept.status,'Accepted');assert.equal(afterAccept.kind,'invite');
 assert.throws(()=>req('phone/invite',{address:aRoom,userId:bUser.id},bt),/owner or co-owner/);
 assert.throws(()=>req('phone/invite',{address:aRoom,userId:aUser.id},at),/Choose another person/);
 assert.throws(()=>req('phone/invite',{address:aRoom,userId:'no-such-user'},at),/not found/);
});
test('phone invite decline and cancel withdraw the invitation; no answer becomes Missed after two minutes',()=>{
 const a=reg('decline-host'),b=reg('decline-guest'),c=reg('decline-outsider');const at=a.token!,bt=b.token!,ct=c.token!,aRoom=a.data.address,bRoom=b.data.address;
 const guestCompany=req('phone/company',{address:bRoom,save:true,name:'Decline Company',listed:true,accepting:true},bt);
 const hostRoomId=(db.prepare('SELECT id FROM shared_rooms WHERE address=?').get(aRoom) as any).id;
 const invite=req('phone/invite',{address:aRoom,number:guestCompany.number},at);
 assert.throws(()=>req('phone/invite-accept',{id:invite.id},ct),/Call not available/);
 assert.throws(()=>req('phone/invite-decline',{id:invite.id},at),/Only the invited person/);
 assert.equal(req('phone/invite-decline',{id:invite.id},bt).ok,true);
 assert.equal(req('phone/inbox',undefined,at).calls.find((x:any)=>x.id===invite.id).status,'Declined');
 assert.equal(req('phone/inbox',undefined,at).calls.find((x:any)=>x.id===invite.id).kind,'invite');
 assert.equal(unusedInvites(hostRoomId),0);
 assert.equal((db.prepare('SELECT count(*) AS n FROM shared_phone_invites WHERE call_id=?').get(invite.id) as any).n,1);
 const second=req('phone/invite',{address:aRoom,number:guestCompany.number},at);assert.equal(unusedInvites(hostRoomId),1);
 assert.equal(req('phone/end',{id:second.id},at).ok,true);assert.equal(unusedInvites(hostRoomId),0);
 assert.equal((db.prepare('SELECT count(*) AS n FROM shared_phone_invites WHERE call_id=?').get(second.id) as any).n,1);
 assert.equal(req('phone/inbox',undefined,at).calls.find((x:any)=>x.id===second.id).kind,'invite');
 assert.throws(()=>req('phone/invite-accept',{id:second.id},bt),/no longer ringing/);
 const third=req('phone/invite',{address:aRoom,number:guestCompany.number},at);
 time+=121000;assert.equal(req('phone/inbox',undefined,at).calls.find((x:any)=>x.id===third.id).status,'Missed');
 assert.equal(req('phone/inbox',undefined,at).calls.find((x:any)=>x.id===third.id).kind,'invite');
 assert.equal(unusedInvites(hostRoomId),0);
 assert.equal((db.prepare('SELECT count(*) AS n FROM shared_phone_invites WHERE call_id=?').get(third.id) as any).n,1);
 assert.throws(()=>req('phone/invite-accept',{id:third.id},bt),/no longer ringing/);
});
test('phone invite into a live meeting carries the meeting flag and the guest joins the same meeting',()=>{
 const a=reg('meeting-host'),b=reg('meeting-guest');const at=a.token!,bt=b.token!,aRoom=a.data.address,bRoom=b.data.address;
 const guestCompany=req('phone/company',{address:bRoom,save:true,name:'Meeting Guest Company',listed:true,accepting:true},bt);
 const hostJoin=req('room/'+aRoom+'/meeting/join',{},at);assert.ok(hostJoin.meetingId);
 const invite=req('phone/invite',{address:aRoom,number:guestCompany.number,meeting:true},at);assert.equal(invite.meeting,true);
 const accepted=req('phone/invite-accept',{id:invite.id},bt);assert.equal(accepted.meeting,true);
 const guestJoin=req('room/'+aRoom+'/meeting/join',{},bt);assert.equal(guestJoin.meetingId,hostJoin.meetingId);
 const poll=req('room/'+aRoom+'/meeting/poll',{after:0,peerId:hostJoin.peerId},at);
 assert.ok(poll.peers.some((p:any)=>p.name==='meeting-guest'));
 assert.ok(poll.peers.some((p:any)=>p.name==='meeting-host'));
});

import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
const folder=mkdtempSync(join(tmpdir(),'leax-room-presence-'));process.env.HQ_DATA_DIR=folder;
const {db}=await import('../src/store.ts');
const {sharedOfficeRequest:request,sharedUser}=await import('../src/shared-offices.ts');
const {memberPresence,guestPresence}=await import('../src/room-presence.ts');
const {setUserAccess}=await import('../src/platform-access.ts');
after(()=>{db.close();rmSync(folder,{recursive:true,force:true});});
test('positions and seats are room-scoped, validated, temporary and revoked with actor access',()=>{
 const now=Date.now(),password='synthetic-presence-password';
 const call=(p:string,v?:any,t='')=>request(p,v===undefined?'GET':'POST',v,t,'presence-test',now);
 const a=call('register',{handle:'presence-owner',name:'Owner',password}),b=call('register',{handle:'presence-member',name:'Member',password}),c=call('register',{handle:'presence-other',name:'Other',password});
 const address=a.data.address,owner=sharedUser(a.token!,now),friend=sharedUser(b.token!,now),other=sharedUser(c.token!,now);
 const invite=call('room/'+address+'/invite',{role:'coworker'},a.token).data;
 call('join',{invitation:invite.invitation},b.token);
 const pose={active:true,cameraMode:'meeting',x:3,z:4,yaw:.2,pitch:.1};
 assert.throws(()=>memberPresence(address,{pose},other,now),/membership/);
 const first=memberPresence(address,{pose},owner,now);
 assert.equal(first.people[0].seat,0);
 const second=memberPresence(address,{pose},friend,now);
 assert.deepEqual(second.people.map(p=>p.seat).sort(),[0,1]);
 assert.ok(second.people.every(p=>!('actor_ref'in p)&&!('password'in p)));
 assert.throws(()=>memberPresence(address,{pose:{...pose,x:NaN}},owner,now),/Invalid office position/);
 const own=memberPresence(address,{pose:{...pose,cameraMode:'explore',x:500}},owner,now);
 assert.equal(own.people.find(p=>p.id===own.selfId)!.seat,null);
 assert.equal(own.people.find(p=>p.id===own.selfId)!.pose.x,10.1);
 const made=call('guest-admin/create',{address,minutes:5},a.token).data,joined=call('guest/redeem',{invitation:made.invitation,name:'Phone guest'}),hash=createHash('sha256').update(joined.token!).digest('hex');
 const guest=guestPresence({pose},hash,now);
 assert.equal(guest.people.find(p=>p.id===guest.selfId)!.role,'guest');
 assert.equal(new Set(guest.people.filter(p=>p.seat!==null).map(p=>p.seat)).size,2);
 assert.equal(memberPresence(c.data.address,{pose},other,now).people.length,1);
 call('guest-admin/revoke',{address,id:made.id},a.token);
 assert.throws(()=>guestPresence({},hash,now),/ended/);
 assert.ok(memberPresence(address,{},owner,now).people.every(p=>p.role!=='guest'));
 call('room/'+address+'/member',{userId:friend.id,role:'remove'},a.token);
 assert.throws(()=>memberPresence(address,{},friend,now),/membership/);
 assert.equal(memberPresence(address,{},owner,now).people.length,1);
 assert.equal(memberPresence(address,{pose},owner,now+15001).people.length,1);
 assert.equal((db.prepare('SELECT count(*) AS n FROM room_live_presence WHERE room_id=(SELECT id FROM shared_rooms WHERE address=?)').get(c.data.address) as any).n,0);
 memberPresence(address,{leave:true},owner,now+15002);
 assert.equal((db.prepare('SELECT count(*) AS n FROM room_live_presence WHERE room_id=(SELECT id FROM shared_rooms WHERE address=?)').get(address) as any).n,0);
 setUserAccess({userId:owner.id,state:'suspended',reason:'Fixture hold'},now);
 assert.throws(()=>memberPresence(address,{},owner,now),/suspended/);
});
